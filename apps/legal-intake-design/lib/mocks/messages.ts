export function getMessagesForCase(caseId: string): Message[] {
  const messages = MOCK_MESSAGES[caseId] ?? [];
  // Timestamps are the source of truth for transcript order, so date separators
  // stay chronological regardless of array authoring order. Array#sort is stable
  // in modern engines, so entries sharing a createdAt keep their written order.
  return [...messages].sort((a, b) => a.createdAt.localeCompare(b.createdAt));
}
