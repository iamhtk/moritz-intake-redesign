/**
 * Admin-facing roll-up of a single law firm: the firm record plus the derived
 * relationship/activity figures the Law Firms table surfaces (primary contact,
 * owner, member count, and case counts by status).
 */
export type LawFirmSummary = {
  company: Company;
  primaryContact: CompanyMember | null;
  owner: CompanyMember | null;
  members: CompanyMember[];
  memberCount: number;
  totalCases: number;
  inProgressCases: number;
  closedCases: number;
};

/** Stable 32-bit hash of a string, used to seed deterministic mock figures. */
function hashString(value: string): number {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash << 5) - hash + value.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Deterministic case figures for a firm: a realistic ~30-50 total with roughly
 * 80-90% closed. Seeded from the company id so the numbers stay stable across
 * renders (and SSR/CSR) while differing per firm.
 */
function mockCaseCounts(companyId: string): {
  total: number;
  inProgress: number;
  closed: number;
} {
  const seed = hashString(companyId);
  const total = 30 + (seed % 21); // 30-50
  const donePercent = 80 + ((seed >> 5) % 11); // 80-90
  const closed = Math.round((total * donePercent) / 100);
  return { total, inProgress: total - closed, closed };
}

function buildLawFirmSummary(company: Company): LawFirmSummary {
  const members = MOCK_COMPANY_MEMBERS[company.id] ?? [];
  const counts = mockCaseCounts(company.id);
  return {
    company,
    members,
    primaryContact:
      members.find((m) => m.isPrimaryContact) ?? members[0] ?? null,
    owner: members.find((m) => m.role === 'OWNER') ?? null,
    memberCount: members.length,
    totalCases: counts.total,
    inProgressCases: counts.inProgress,
    closedCases: counts.closed,
  };
}

export function getLawFirmSummaries(): LawFirmSummary[] {
  return MOCK_COMPANIES.filter((c) => c.type === 'LEGAL').map(
    buildLawFirmSummary,
  );
}

export function getLawFirmSummary(id: string): LawFirmSummary | undefined {
  const company = MOCK_COMPANIES.find((c) => c.id === id && c.type === 'LEGAL');
  return company ? buildLawFirmSummary(company) : undefined;
}
